const ALLOWED_RISKS=new Set(['A0','A1','A2']);
const ALLOWED_BACKENDS=new Set(['self-hosted','copilot']);
const sectionKey=(value='')=>String(value).trim().toLowerCase().replace(/[^a-z0-9]+/g,'_').replace(/^_|_$/g,'');
const clean=(value='')=>String(value||'').replace(/^[-*+]\s+/,'').replace(/^\d+[.)]\s+/,'').trim();
const labelsOf=(issue)=>new Set((issue?.labels||[]).map(x=>typeof x==='string'?x:x?.name).filter(Boolean));

export function parseMissionPacket(body='',title=''){
  const fields={};const sections={};let current=null;
  for(const raw of String(body||'').split(/\r?\n/)){
    const heading=raw.match(/^###\s+(.+?)\s*$/);
    if(heading){current=sectionKey(heading[1]);sections[current]=sections[current]||[];continue}
    const field=raw.match(/^([A-Z][A-Z0-9_]+):\s*(.*?)\s*$/);
    if(field&&!current){fields[field[1].toLowerCase()]=field[2];continue}
    if(current)sections[current].push(raw);
  }
  const text=(key)=>(sections[key]||[]).map(x=>x.trim()).filter(Boolean).join(' ').trim();
  const list=(key)=>(sections[key]||[]).map(clean).filter(Boolean);
  return {
    title:String(title||''),
    approval:String(fields.approval||'').toLowerCase(),
    project:String(fields.project||''),
    repository:String(fields.repository||''),
    riskClass:String(fields.risk_class||'').toUpperCase(),
    runnerMode:String(fields.runner_mode||'auto').toLowerCase(),
    runnerBackend:String(fields.runner_backend||'self-hosted').toLowerCase(),
    snapshot:String(fields.snapshot||''),
    mission:text('approved_mission'),
    whyNow:text('why_now'),
    doneWhen:list('done_when'),
    constraints:list('constraints'),
    forbidden:list('forbidden'),
    executionBoundary:text('execution_boundary')
  };
}

export function validateMissionPacket(packet,{owner='mikelninh'}={}){
  const errors=[];
  if(packet.approval!=='approved')errors.push('APPROVAL must be approved');
  if(!packet.project)errors.push('PROJECT is required');
  if(!new RegExp(`^${owner.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}\\/[A-Za-z0-9._-]+$`).test(packet.repository))errors.push(`REPOSITORY must stay inside ${owner}/*`);
  if(!ALLOWED_RISKS.has(packet.riskClass))errors.push('Only A0-A2 missions may enter the automatic runner');
  if(!packet.mission)errors.push('Approved mission text is required');
  if(!packet.doneWhen.length)errors.push('At least one done-when criterion is required');
  if(!packet.constraints.length)errors.push('At least one constraint is required');
  if(!packet.forbidden.length)errors.push('At least one forbidden action is required');
  if(!/A0[–-]A2/.test(packet.executionBoundary))errors.push('Execution boundary must explicitly preserve A0-A2');
  if(!['auto','dry-run'].includes(packet.runnerMode))errors.push('RUNNER_MODE must be auto or dry-run');
  if(!ALLOWED_BACKENDS.has(packet.runnerBackend))errors.push(`RUNNER_BACKEND must be one of: ${[...ALLOWED_BACKENDS].join(', ')}`);
  return {ok:errors.length===0,errors};
}

export function assertMissionPacket(packet,options){const result=validateMissionPacket(packet,options);if(!result.ok)throw new Error(result.errors.join('; '));return packet}
